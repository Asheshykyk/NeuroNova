import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import hardhat from 'hardhat';
const { ethers, network } = hardhat;

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Local deployment script for EvidenceAnchor.sol
 * 
 * 1. Connects to local JSON-RPC provider (http://127.0.0.1:8545 or hardhat in-process).
 * 2. Deploys EvidenceAnchor.sol.
 * 3. Registers the Vault Signer address derived from VAULT_SIGNER_PRIVATE_KEY for AGENT_SOURCE_ID.
 * 4. Outputs the deployed contract address to lab/contract-address.env.
 */
async function main() {
  console.log('============================================================');
  console.log(`[Deploy-Local] Deploying EvidenceAnchor to: ${network.name}`);
  console.log('============================================================\n');

  const [deployer] = await ethers.getSigners();
  if (!deployer) {
    throw new Error('No deployer signer configured for local network');
  }

  const deployerAddress = await deployer.getAddress();
  console.log(`Deployer / Relayer Address: ${deployerAddress}`);

  // Resolve source ID and vault signer
  const sourceId = process.env.AGENT_SOURCE_ID?.trim() || '0x1111111111111111111111111111111111111111111111111111111111111111';
  const vaultSignerKey = process.env.VAULT_SIGNER_PRIVATE_KEY?.trim();
  if (!vaultSignerKey) throw new Error('VAULT_SIGNER_PRIVATE_KEY is required (run: node scripts/gen-lab-env.mjs)');
  const vaultSignerAddress = ethers.computeAddress(vaultSignerKey);

  console.log(`Target Source ID:           ${sourceId}`);
  console.log(`Authorized Vault Signer:    ${vaultSignerAddress}\n`);

  console.log('Deploying EvidenceAnchor contract...');
  const EvidenceAnchorFactory = await ethers.getContractFactory('EvidenceAnchor');
  const contract = await EvidenceAnchorFactory.deploy();
  await contract.waitForDeployment();

  const contractAddress = await contract.getAddress();
  const txHash = contract.deploymentTransaction()?.hash;

  console.log(`✓ EvidenceAnchor deployed at: ${contractAddress} (tx: ${txHash})`);

  // Register source with authorized vault signer
  console.log(`Registering source ${sourceId} with signer ${vaultSignerAddress}...`);
  const regTx = await contract.registerSource(sourceId, vaultSignerAddress);
  await regTx.wait();
  console.log(`✓ Source registered successfully (tx: ${regTx.hash})`);

  // Verify registration
  const sourceInfo = await contract.getSource(sourceId);
  if (!sourceInfo.registered || sourceInfo.signer.toLowerCase() !== vaultSignerAddress.toLowerCase()) {
    throw new Error(`Failed to verify registered signer for source ${sourceId}`);
  }
  console.log(`✓ On-chain source registration verified.`);

  // Write lab/contract-address.env
  const labDir = path.resolve(__dirname, '../../lab');
  if (!fs.existsSync(labDir)) {
    fs.mkdirSync(labDir, { recursive: true });
  }

  const envFilePath = path.join(labDir, 'contract-address.env');
  const envContent = [
    `# Generated by blockchain/scripts/deploy-local.ts at ${new Date().toISOString()}`,
    `EVIDENCE_ANCHOR_LOCAL_ADDRESS=${contractAddress}`,
    `LOCAL_RPC_URL=http://127.0.0.1:8545`,
    `LOCAL_CHAIN_ID=31337`,
    `LOCAL_RELAYER_PRIVATE_KEY=0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80`,
    `VAULT_SIGNER_ADDRESS=${vaultSignerAddress}`,
    `AGENT_SOURCE_ID=${sourceId}`,
    ''
  ].join('\n');

  fs.writeFileSync(envFilePath, envContent, 'utf8');
  console.log(`✓ Exported local configuration to: ${envFilePath}\n`);

  return {
    contractAddress,
    deployerAddress,
    vaultSignerAddress,
    sourceId
  };
}

main().catch((error) => {
  console.error('[Deploy-Local] Fatal Error:', error);
  process.exitCode = 1;
});
